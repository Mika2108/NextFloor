// Writes preview/basic-types.js: the basic furniture models (not those of the packs) with their sizes and names in German and
// English, so that the online demo's model showcase can lay them out. Run: node --experimental-strip-types tools/make_showcase_types.mjs
import { writeFileSync } from "node:fs";
import { FURNITURE_GROUPS, FURNITURE_SIZE } from "../frontend/src/model.ts";
import { translate } from "../frontend/src/i18n.ts";

const name = (lang, key) => translate({ language: lang }, key);
const groups = Object.entries(FURNITURE_GROUPS).map(([id, types]) => ({
  id,
  name: { de: name("de", `furn_group_${id}`), en: name("en", `furn_group_${id}`) },
  items: types.map((type) => ({ type, size: FURNITURE_SIZE[type], name: { de: name("de", `furn_${type}`), en: name("en", `furn_${type}`) } })),
}));
writeFileSync(new URL("../preview/basic-types.js", import.meta.url), `// generated by tools/make_showcase_types.mjs\nwindow.BASIC_TYPES = ${JSON.stringify(groups)};\n`);
console.log(groups.map((g) => `${g.id}: ${g.items.length}`).join(", "));
